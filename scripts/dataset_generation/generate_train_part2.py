def build_conversation(conv_id, scenario, micro_turns):
    topic = f"{scenario}_{conv_id}"
    messages = [{"role": "system", "content": SYSTEM_PROMPT}]
    for turn in micro_turns:
        messages.append({"role": "user", "content": turn["user"]})
        messages.append({"role": "assistant", "content": turn["assistant"]})

    return {
        "id": conv_id,
        "scenario": scenario,
        "topic": topic,
        "micro_turns": micro_turns,
        "messages": messages,
    }


def main():
    train_path = "/home/aditya/Desktop/STUDY/TalkAI/data/duplexcascade_synthetic/micro_turns_train.jsonl"
    out_path = "/home/aditya/Desktop/STUDY/TalkAI/data/duplexcascade_synthetic/train_part2.jsonl"

    with open(train_path, "r", encoding="utf-8") as f:
        lines = [json.loads(line) for line in f]

    seen_turns = set()
    duplicates = []
    for idx, item in enumerate(lines):
        turn_str = json.dumps(item["micro_turns"])
        if turn_str in seen_turns:
            duplicates.append((idx, item))
        else:
            seen_turns.add(turn_str)

    batch2 = duplicates[130:260]
    assert len(batch2) == 130, f"Expected 130 duplicates, got {len(batch2)}"

    scenario_counters = Counter()
    results = []

    for orig_idx, orig_item in batch2:
        cid = orig_item["id"]
        sc = orig_item["scenario"]
        sc_idx = scenario_counters[sc]
        scenario_counters[sc] += 1

        assert sc in DIALOGUES, f"Scenario {sc} not in DIALOGUES"
        assert sc_idx < len(DIALOGUES[sc]), f"Scenario {sc} ran out of templates (needed {sc_idx+1}, have {len(DIALOGUES[sc])})"

        raw_turns = DIALOGUES[sc][sc_idx]
        assert len(raw_turns) % 2 == 0, f"raw_turns must have even number of items, got {len(raw_turns)}"
        micro_turns = []
        for i in range(0, len(raw_turns), 2):
            assert raw_turns[i][0] == "user"
            assert raw_turns[i+1][0] == "assistant"
            micro_turns.append({"user": raw_turns[i][1], "assistant": raw_turns[i+1][1]})

        conv = build_conversation(cid, sc, micro_turns)
        results.append(conv)

    print(f"Generated {len(results)} conversations.")
    print("Scenario distribution:", scenario_counters)

    with open(out_path, "w", encoding="utf-8") as f:
        for item in results:
            f.write(json.dumps(item, ensure_ascii=False) + "\n")

    print(f"Successfully saved to {out_path}")


if __name__ == "__main__":
    main()
